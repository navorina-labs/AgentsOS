/**
 * HTML-отчёт для safetyos analyze.
 */
import type { AnalyzeReport } from "../types/threat-model.js";

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

const TIER_COLOR: Record<string, string> = {
  critical: "#dc2626",
  high: "#ea580c",
  medium: "#ca8a04",
  low: "#16a34a",
};

export function renderAnalyzeHtml(report: AnalyzeReport): string {
  const flowRows = report.flows
    .map((f) => {
      const findings = f.findings
        .map(
          (x) =>
            `<li><strong>${escapeHtml(x.severity)}</strong> ${escapeHtml(x.code)}: ${escapeHtml(x.message)}</li>`,
        )
        .join("");
      const recs = f.recommendations
        .map((r) => `<li>${escapeHtml(r)}</li>`)
        .join("");
      return `
      <section class="flow" style="border-left: 4px solid ${TIER_COLOR[f.tier] ?? "#666"}">
        <h3>${escapeHtml(f.name)} <span class="tier">${escapeHtml(f.tier)}</span> ${f.score}/100</h3>
        <p class="meta">id=${escapeHtml(f.id)} · confidentiality ${f.confidentiality_years}y · mosca_flow=${f.mosca_flow_at_risk}</p>
        <ul>${findings}</ul>
        ${recs ? `<h4>Рекомендации</h4><ul>${recs}</ul>` : ""}
      </section>`;
    })
    .join("");

  return `<!DOCTYPE html>
<html lang="ru">
<head>
  <meta charset="utf-8"/>
  <title>SafetyOS — ${escapeHtml(report.organization)}</title>
  <style>
    body { font-family: system-ui, sans-serif; max-width: 900px; margin: 2rem auto; padding: 0 1rem; background: #0f1419; color: #e7ecf3; }
    h1 { font-size: 1.5rem; }
    .mosca { background: #1a2332; padding: 1rem; border-radius: 8px; margin: 1rem 0; }
    .at-risk { color: #f87171; font-weight: bold; }
    .flow { background: #1a2332; padding: 1rem; margin: 1rem 0; border-radius: 8px; }
    .tier { text-transform: uppercase; font-size: 0.75rem; padding: 0.15rem 0.5rem; border-radius: 4px; background: #334155; }
    .meta { color: #94a3b8; font-size: 0.875rem; }
    li { margin: 0.35rem 0; }
  </style>
</head>
<body>
  <h1>SafetyOS — ${escapeHtml(report.organization)}</h1>
  <div class="mosca">
    <p>Mosca: <span class="${report.mosca.at_risk ? "at-risk" : ""}">at_risk=${report.mosca.at_risk}</span></p>
    <p>margin ${report.mosca.margin_years} лет · x_max=${report.mosca.x_max_years}y · y=${report.mosca.y_migration_years}y · z=${report.mosca.z_horizon_years}y</p>
    <p>Потоки: ${report.summary.total_flows} · critical=${report.summary.critical} · high=${report.summary.high} · medium=${report.summary.medium} · low=${report.summary.low}</p>
  </div>
  ${flowRows}
  <footer><p style="color:#64748b;font-size:0.8rem">Generated by SafetyOS</p></footer>
</body>
</html>`;
}
